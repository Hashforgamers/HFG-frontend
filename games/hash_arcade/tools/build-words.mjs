// Regenerates src/games/_shared/dictionary.ts from SCOWL (npm: wordlist-english).
// Run: node tools/build-words.mjs. The output is committed so app builds don't need it.
import { readFileSync, writeFileSync } from 'node:fs';

const base = 'node_modules/wordlist-english/';
const load = (f) => JSON.parse(readFileSync(`${base}${f}.json`, 'utf8'));
const ok = (w) => /^[a-z]{3,7}$/.test(w);

